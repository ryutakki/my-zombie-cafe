// Crops, downsizes and packs Craftpix PNG sequences into horizontal strips + a JS manifest.
// usage: node build-sprites.js <extractedRoot> <projectRoot>
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const [SRC, OUT] = process.argv.slice(2);
const TARGET_H = 128; // standing height of the character in output pixels

const CHARS = {
  pirate_zombie: 'pirate/Pirate Zombie',
  squidman: 'pirate/Squidman',
  pirate_leader: 'pirate/Pirate Leader',
  assassin: 'bandit1/Assassin',
  robber: 'bandit1/Robber',
  thug: 'bandit1/Thug',
};

// [animKey, folder, frameStep, fps, loop]
const ANIMS = [];
for (const d of ['Front', 'Back', 'Left', 'Right']) {
  ANIMS.push([`idle_${d.toLowerCase()}`, `${d} - Idle`, 2, 10, true]);
  ANIMS.push([`walk_${d.toLowerCase()}`, `${d} - Walking`, 2, 14, true]);
}
for (const d of ['Left', 'Right']) {
  ANIMS.push([`attack_${d.toLowerCase()}`, `${d} - Attacking`, 1, 18, false]);
  ANIMS.push([`hurt_${d.toLowerCase()}`, `${d} - Hurt`, 2, 12, false]);
}
ANIMS.push(['die', 'Dying', 1, 12, false]);

async function bbox(file) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] > 8) {
        if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
      }
    }
  }
  return { x0, y0, x1, y1, w: info.width, h: info.height };
}

function framesOf(dir, step) {
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.png')).sort();
  return files.filter((_, i) => i % step === 0).map(f => path.join(dir, f));
}

(async () => {
  const manifest = {};
  for (const [key, rel] of Object.entries(CHARS)) {
    const seqRoot = path.join(SRC, rel, 'PNG', 'PNG Sequences');
    const anims = ANIMS.map(([k, folder, step, fps, loop]) => ({ k, files: framesOf(path.join(seqRoot, folder), step), fps, loop }));
    // union bbox across every kept frame so all frames share one anchor
    let U = { x0: 1e9, y0: 1e9, x1: -1, y1: -1 };
    for (const a of anims) for (const f of a.files) {
      const b = await bbox(f);
      U = { x0: Math.min(U.x0, b.x0), y0: Math.min(U.y0, b.y0), x1: Math.max(U.x1, b.x1), y1: Math.max(U.y1, b.y1) };
    }
    const idle = await bbox(anims[0].files[0]);
    const scale = TARGET_H / (idle.y1 - idle.y0 + 1);
    const cw = U.x1 - U.x0 + 1, ch = U.y1 - U.y0 + 1;
    const fw = Math.ceil(cw * scale), fh = Math.ceil(ch * scale);
    const outDir = path.join(OUT, 'assets', 'sprites', key);
    fs.mkdirSync(outDir, { recursive: true });
    const entry = {
      fw, fh,
      ax: Math.round(((idle.x0 + idle.x1) / 2 - U.x0) * scale), // feet anchor x
      ay: Math.round((idle.y1 - U.y0) * scale),                 // feet anchor y
      anims: {},
    };
    for (const a of anims) {
      const tiles = await Promise.all(a.files.map(f =>
        sharp(f).extract({ left: U.x0, top: U.y0, width: cw, height: ch }).resize(fw, fh).png().toBuffer()));
      await sharp({ create: { width: fw * tiles.length, height: fh, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
        .composite(tiles.map((t, i) => ({ input: t, left: i * fw, top: 0 })))
        .png({ compressionLevel: 9, palette: false })
        .toFile(path.join(outDir, `${a.k}.png`));
      entry.anims[a.k] = { n: tiles.length, fps: a.fps, loop: a.loop };
    }
    manifest[key] = entry;
    console.log(key, `${fw}x${fh}`, 'scale', scale.toFixed(3));
  }
  fs.mkdirSync(path.join(OUT, 'js'), { recursive: true });
  fs.writeFileSync(path.join(OUT, 'js', 'sprites-manifest.js'),
    '// Generated by tools/build-sprites.js — do not edit by hand.\nwindow.SPRITES = ' + JSON.stringify(manifest, null, 1) + ';\n');
})();
